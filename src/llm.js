const MOCKS = { t2: MOCK_T2, t3: MOCK_T3, t4: MOCK_T4 };

export async function quietGenerate(messages, label = 'ananke', options = {}) {
    const s = getSettings();
    if (s.mock) {
        const mock = MOCKS[label];
        if (mock) return JSON.stringify(mock);
        return '{}';
    }
    if (!s.api.url || !s.api.key) {
        throw new Error('未配置 API：请在面板填写 API 地址与 Key，或开启 mock 调试模式');
    }
    return await chatCompletion({
        url: s.api.url,
        key: s.api.key,
        model: s.api.model,
        messages,
        temperature: options.temperature ?? 0.7,
        maxTokens: options.maxTokens ?? 4000,
        timeoutMs: options.timeoutMs ?? 120000,
    });
}
